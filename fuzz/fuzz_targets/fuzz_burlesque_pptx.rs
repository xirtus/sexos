fn exercise_deck(deck: burlesque_core::Deck) {
    let mut slide_buf = vec![0u32; 64 * 36];
    if let Some(slide) = deck.get_slide(0) {
        burlesque_core::render::render_slide(
            slide,
            &deck.theme,
            deck.aspect_ratio,
            &mut slide_buf,
            64,
            36,
        );
    }

    let session = burlesque_core::presenter::PresenterSession::new(deck);
    let mut pres_buf_small = vec![0u32; 128 * 72];
    burlesque_core::presenter::render_presenter_view(&session, &mut pres_buf_small, 128, 72);

    let mut pres_buf_large = vec![0u32; 320 * 200];
    burlesque_core::presenter::render_presenter_view(&session, &mut pres_buf_large, 320, 200);
}

fuzz_target!(|data: &[u8]| {
    if data.is_empty() {
        return;
    }

    // 1. Raw byte import
    if let Ok(deck) = burlesque_core::import_pptx(data) {
        exercise_deck(deck);
    }

    // 2. Structured uncompressed ZIP OOXML import
    let part_choice = data[0] % 8;
    let payload = &data[1..];

    let mut content_types = MINIMAL_CONTENT_TYPES;
    let mut pres_xml = MINIMAL_PRESENTATION_XML;
    let mut pres_rels = MINIMAL_PRESENTATION_RELS;
    let mut theme_xml = MINIMAL_THEME_XML;
    let mut slide_xml = MINIMAL_SLIDE_XML;
    let mut slide_rels = MINIMAL_SLIDE_RELS;
    let mut notes_xml = MINIMAL_NOTES_SLIDE;
    let mut image_png = TINY_PNG_1X1;

    match part_choice {
        0 => content_types = payload,
        1 => pres_xml = payload,
        2 => pres_rels = payload,
        3 => theme_xml = payload,
        4 => slide_xml = payload,
        5 => slide_rels = payload,
        6 => notes_xml = payload,
        _ => image_png = payload,
    }

    let entries = [
        ("[Content_Types].xml", content_types),
        ("_rels/.rels", MINIMAL_ROOT_RELS),
        ("ppt/presentation.xml", pres_xml),
        ("ppt/_rels/presentation.xml.rels", pres_rels),
        ("ppt/theme/theme1.xml", theme_xml),
        ("ppt/slides/slide1.xml", slide_xml),
        ("ppt/slides/_rels/slide1.xml.rels", slide_rels),
        ("ppt/notesSlides/notesSlide1.xml", notes_xml),
        ("ppt/media/image1.png", image_png),
    ];

    let zip_bytes = make_stored_zip(&entries);
    if let Ok(deck) = burlesque_core::import_pptx(&zip_bytes) {
        exercise_deck(deck);
    }
});
