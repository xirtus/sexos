#!/usr/bin/env python3
"""Writes crates/sex-keymap/src/compose_data.rs from Python's Unicode data.

Two tables, both sorted for binary search:
  ACCENTED: (combining mark, base letter) -> precomposed letter, for dead keys.
  SEQUENCES: Compose-key sequences of two or three characters -> one character.
The sequences follow the familiar X11 Compose conventions (", ', `, ^, ~, ",",
o, c, /, =, -, _ with a letter, in either order), written here as our own data.
Run: python3 scripts/gen_keymap_compose.py
"""
import unicodedata, sys
from pathlib import Path

MARKS = {
    0x300: '`', 0x301: "'", 0x302: '^', 0x303: '~', 0x304: '_', 0x306: 'U',
    0x307: '.', 0x308: '"', 0x30A: 'o', 0x30B: '=', 0x30C: 'c', 0x323: '!',
    0x327: ',', 0x328: ';',
}
accented = {}
# Latin, Greek and Cyrillic letters with one mark: Latin-1 through Latin Extended
# Additional, plus Greek tonos/dialytika and Cyrillic ё/й style letters.
ranges = [(0xC0, 0x250), (0x1E00, 0x1F00), (0x386, 0x3D0), (0x400, 0x460)]
for lo, hi in ranges:
    for cp in range(lo, hi):
        ch = chr(cp)
        d = unicodedata.decomposition(ch)
        if not d or d.startswith('<'):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        base, mark = parts
        if mark not in MARKS and mark not in (0x301,):
            continue
        # Base must itself be a plain letter (one level of marks only).
        if unicodedata.decomposition(chr(base)):
            continue
        accented.setdefault((mark, base), cp)

seq = {}
def add(keys, out, force=False):
    if keys in seq and not force:
        return
    seq[keys] = out

for (mark, base), cp in sorted(accented.items()):
    m = MARKS.get(mark)
    if m is None or base >= 0x370:
        continue
    b = chr(base)
    add((m, b), cp)
for (mark, base), cp in sorted(accented.items()):
    m = MARKS.get(mark)
    if m is None or base >= 0x370:
        continue
    b = chr(base)
    add((b, m), cp)

specials = {
    'ss': 'ß', 'SS': 'ẞ', 'ae': 'æ', 'AE': 'Æ', 'oe': 'œ', 'OE': 'Œ', 'o/': 'ø', 'O/': 'Ø',
    '/o': 'ø', '/O': 'Ø', 'th': 'þ', 'TH': 'Þ', 'dh': 'ð', 'DH': 'Ð', 'd-': 'đ', 'D-': 'Đ',
    'l/': 'ł', 'L/': 'Ł', '/l': 'ł', '/L': 'Ł', 'ng': 'ŋ', 'NG': 'Ŋ', 'i.': 'ı',
    '=e': '€', 'e=': '€', 'C=': '€', '=C': '€', 'L-': '£', '-L': '£', 'Y=': '¥', '=Y': '¥',
    'c/': '¢', '/c': '¢', 'c|': '¢', 'ox': '¤', 'xo': '¤', 'R=': '₹', 'P=': '₽', 'W=': '₩',
    '!!': '¡', '??': '¿', '<<': '«', '>>': '»', '.<': '‹', '.>': '›',
    '<"': '“', '>"': '”', ',"': '„', "<'": '‘', ">'": '’', ",'": '‚',
    'oc': '©', 'oC': '©', 'Oc': '©', 'or': '®', 'oR': '®', 'Or': '®', 'tm': '™', 'TM': '™',
    'so': '§', 'os': '§', 'pp': '¶', 'P!': '¶', '!p': '¶',
    '+-': '±', '-+': '±', 'xx': '×', ':-': '÷', '-:': '÷', '=/': '≠', '/=': '≠',
    '<=': '≤', '>=': '≥', '<_': '≤', '>_': '≥', '~~': '≈', 'oo': '°', '*0': '°',
    '12': '½', '13': '⅓', '14': '¼', '34': '¾', '18': '⅛',
    '^1': '¹', '^2': '²', '^3': '³', '1^': '¹', '2^': '²', '3^': '³',
    '_0': '₀', '_1': '₁', '_2': '₂', '_3': '₃',
    '..': '…', '.-': '·', '-.': '·', '.^': '·', 'mu': 'µ', '/u': 'µ',
    '->': '→', '<-': '←', '|^': '↑', '|v': '↓', '=>': '⇒', '<>': '↔',
    '<3': '♥', ':)': '☺', ':(': '☹', 'a_': 'ª', 'o_': 'º', '_a': 'ª', '_o': 'º',
    '||': '¦', '-,': '¬', ',-': '¬', '\'\'': '´', '""': '¨', ',,': '¸', '__': '¯',
    '#b': '♭', '##': '♯', '#f': '♮', 'sm': '℠',
}
for k, v in specials.items():
    add(tuple(k), ord(v), force=True)
three = {
    '---': '—', '--.': '–', '--': None, '...': '…', '=>>': '⟹', '1/2': '½', '1/4': '¼',
    '3/4': '¾', '1/3': '⅓', '2/3': '⅔', '<<<': '⋘', 'nu.': 'ν',
}
for k, v in three.items():
    if v:
        add(tuple(k), ord(v), force=True)

# A two-key sequence that is also the start of a three-key one would never be
# reachable as three: keep only the shorter where they collide.
for k in list(seq):
    if len(k) == 3 and k[:2] in seq:
        del seq[k]

def rs(c):
    return "'\\u{%x}'" % ord(c)

out = []
out.append('// SPDX-License-Identifier: GPL-2.0-or-later OR MIT')
out.append('// Generated by scripts/gen_keymap_compose.py from Unicode decompositions. Do not edit.')
out.append('')
out.append('/// (combining mark, base) -> precomposed scalar, sorted.')
out.append('pub static ACCENTED: [(u32, u32, u32); %d] = [' % len(accented))
for (mark, base), cp in sorted(accented.items()):
    out.append('    (0x%x, 0x%x, 0x%x),' % (mark, base, cp))
out.append('];')
out.append('')
out.append('/// Compose sequences, padded with NUL to three keys, sorted.')
items = sorted(((tuple(ord(c) for c in k) + (0,) * (3 - len(k)), v) for k, v in seq.items()))
out.append('pub static SEQUENCES: [([u32; 3], u32); %d] = [' % len(items))
for k, v in items:
    out.append('    ([0x%x, 0x%x, 0x%x], 0x%x),' % (k + (v,)))
out.append('];')
Path(sys.argv[1] if len(sys.argv) > 1 else 'crates/sex-keymap/src/compose_data.rs').write_text('\n'.join(out) + '\n')
print('accented', len(accented), 'sequences', len(items))
