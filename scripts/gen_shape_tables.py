#!/usr/bin/env python3
"""Writes crates/sex-shape/src/arabic_forms.rs: each Arabic letter's isolated, final,
initial and medial presentation forms, from Unicode compatibility decompositions.
Run: python3 scripts/gen_shape_tables.py"""
import unicodedata
from pathlib import Path
forms = {}
for cp in list(range(0xFE70, 0xFF00)) + list(range(0xFB50, 0xFE00)):
    d = unicodedata.decomposition(chr(cp))
    if not d.startswith('<'):
        continue
    tag, *rest = d.split()
    if len(rest) != 1:
        continue
    base = int(rest[0], 16)
    if 0x600 <= base <= 0x6FF:
        forms.setdefault(base, {}).setdefault(tag, cp)
rows = []
for base in sorted(forms):
    f = forms[base]
    row = (base, f.get('<isolated>', 0), f.get('<final>', 0), f.get('<initial>', 0), f.get('<medial>', 0))
    if row[1] or row[2]:
        rows.append(row)
out = ['// SPDX-License-Identifier: GPL-2.0-or-later OR MIT',
       '// Generated from Unicode compatibility decompositions (<isolated>/<final>/<initial>/<medial>).',
       '// Do not edit: regenerate with scripts/gen_shape_tables.py.', '',
       '/// (letter, isolated, final, initial, medial); 0 where the form does not exist.',
       'pub static FORMS: [(u16, u16, u16, u16, u16); %d] = [' % len(rows)]
out += ['    (0x%04x, 0x%04x, 0x%04x, 0x%04x, 0x%04x),' % r for r in rows]
out.append('];')
Path(__file__).resolve().parents[1].joinpath('crates/sex-shape/src/arabic_forms.rs').write_text('\n'.join(out) + '\n')
print(len(rows), 'letters')

# Bidi classes as runs, for crates/sex-shape/src/bidi_classes.rs. Explicit
# embedding/isolate controls count as BN (the line algorithm ignores them).
CLS = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON']
runs, cur, start = [], None, 0
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        c = 'L'
    else:
        c = unicodedata.bidirectional(chr(cp)) or 'L'
        if c in ('LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI'):
            c = 'BN'
        if not unicodedata.bidirectional(chr(cp)):  # unassigned: the block's default
            if 0x0590 <= cp <= 0x05FF or 0x07C0 <= cp <= 0x085F or 0xFB1D <= cp <= 0xFB4F or 0x10800 <= cp <= 0x10FFF or 0x1E800 <= cp <= 0x1EFFF:
                c = 'R'
            elif 0x0600 <= cp <= 0x07BF or 0x0860 <= cp <= 0x08FF or 0xFB50 <= cp <= 0xFDCF or 0xFDF0 <= cp <= 0xFDFF or 0xFE70 <= cp <= 0xFEFF:
                c = 'AL'
    if c != cur:
        if cur is not None:
            runs.append((start, cur))
        cur, start = c, cp
runs.append((start, cur))
out = ['// SPDX-License-Identifier: GPL-2.0-or-later OR MIT',
       '// Generated by scripts/gen_shape_tables.py from Unicode bidi classes. Do not edit.', '',
       '/// (first scalar, class) runs covering every scalar; class indexes `super::Class`.',
       'pub static RUNS: [(u32, u8); %d] = [' % len(runs)]
out += ['    (0x%x, %d),' % (s, CLS.index(c)) for s, c in runs]
out.append('];')
Path(__file__).resolve().parents[1].joinpath('crates/sex-shape/src/bidi_classes.rs').write_text('\n'.join(out) + '\n')
print(len(runs), 'bidi runs')

# Which characters take two cells of a text grid: East Asian Width W or F
# (assigned characters that are not marks, format characters or the Hangul filler).
wide = []
for cp in range(0x110000):
    c = chr(cp)
    w = unicodedata.east_asian_width(c) in ('W', 'F') and unicodedata.category(c) not in ('Mn', 'Mc', 'Me', 'Cf', 'Cn') and cp != 0x3164
    if w:
        if wide and wide[-1][1] == cp - 1: wide[-1][1] = cp
        else: wide.append([cp, cp])
out = ['// SPDX-License-Identifier: GPL-2.0-or-later OR MIT',
       '// Generated from Unicode East Asian Width (W, F) of assigned characters (Unicode %s).' % unicodedata.unidata_version,
       '// Do not edit: regenerate with scripts/gen_shape_tables.py.', '',
       '/// Inclusive ranges of characters that take two text cells, sorted.',
       'pub static WIDE: [(u32, u32); %d] = [' % len(wide)]
out += ['    (0x%05x, 0x%05x),' % (a, b) for a, b in wide]
out.append('];')
Path(__file__).resolve().parent.parent.joinpath('crates/sex-shape/src/wide_table.rs').write_text('\n'.join(out) + '\n')
