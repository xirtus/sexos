"""Builds crates/sex-gate/src/template.rs from crates/sex-gate/stub.S.

The stub is assembled once with base values for every symbol, then once more per symbol
with a value that differs in every byte. The bytes that change are that symbol's patch
sites. The Rust generator then only patches fields and never assembles.

  gen_gate_stub.py           rewrite template.rs
  gen_gate_stub.py --check   exit 1 if template.rs is stale (needs GNU as + nm)
"""
import os, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'crates/sex-gate/stub.S'
OUT = ROOT / 'crates/sex-gate/src/template.rs'

# name: (width in bytes, base, variant). Base values force the long encodings (imm32,
# disp32) that every real value needs, and every byte differs between base and variant.
FIELDS = {
    'MATRIX': (8, 0x0101010101010101, 0x0202020202020202),
    'STUBID': (4, 0x01010101, 0x02020202),
    'PKRU_G': (4, 0x01010101, 0x02020202),
    'PKRU_E': (4, 0x01010111, 0x02020212),
    'PKRU_C': (4, 0x01010121, 0x02020222),
    'CPAGE': (4, 0x01010101, 0x02020202),
    'EPAGE': (4, 0x01010141, 0x02020242),
    'EMASK': (8, 0x0101010101010101, 0x0202020202020202),
    'ENTRY': (4, 0x01010101, 0x02020202),
}
LABELS = ('gate_wrpkru_1', 'gate_wrpkru_2', 'gate_wrpkru_3', 'gate_wrpkru_4', 'gate_return', 'gate_stub_end')


def assemble(values, tmp):
    obj = Path(tmp) / 'stub.o'
    args = ['as', '--64', '-o', str(obj)]
    for name, value in values.items():
        args += ['--defsym', f'{name}={value:#x}']
    subprocess.run(args + [str(SRC)], check=True)
    text = subprocess.run(['objcopy', '-O', 'binary', '--only-section=.text', str(obj), str(Path(tmp) / 'stub.bin')], check=True)
    data = (Path(tmp) / 'stub.bin').read_bytes()
    syms = {}
    for line in subprocess.run(['nm', str(obj)], capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] in LABELS:
            syms[parts[2]] = int(parts[0], 16)
    return data, syms


def runs(a, b):
    out, i = [], 0
    while i < len(a):
        if a[i] != b[i]:
            j = i
            while j < len(a) and a[j] != b[j]:
                j += 1
            out.append((i, j - i))
            i = j
        else:
            i += 1
    return out


def render():
    with tempfile.TemporaryDirectory() as tmp:
        base = {name: f[1] for name, f in FIELDS.items()}
        data, syms = assemble(base, tmp)
        sites = []
        for name, (width, b, v) in FIELDS.items():
            other, _ = assemble({**base, name: v}, tmp)
            if len(other) != len(data):
                raise SystemExit(f'{name}: encoding size changed between values')
            found = runs(data, other)
            if not found:
                raise SystemExit(f'{name}: no patch site')
            for at, n in found:
                if n != width:
                    raise SystemExit(f'{name}: site at {at:#x} is {n} bytes, expected {width}')
                addend = int.from_bytes(data[at:at + width], 'little', signed=False) - b
                sites.append((name, at, width, addend))
    wr = [i for i in range(len(data) - 2) if data[i:i + 3] == b'\x0f\x01\xef']
    if wr != [syms[f'gate_wrpkru_{k}'] for k in (1, 2, 3, 4)]:
        raise SystemExit(f'WRPKRU bytes {wr} are not exactly the four gate_wrpkru labels')
    sites.sort(key=lambda s: s[1])
    lines = ['// SPDX-License-Identifier: GPL-3.0-only',
             '// Generated by scripts/gen_gate_stub.py from crates/sex-gate/stub.S. Do not edit.',
             '',
             'use crate::Field;',
             '',
             f'pub const LEN: usize = {len(data)};',
             '',
             '/// The stub assembled with base values; every site below is overwritten.',
             'pub const TEMPLATE: [u8; LEN] = [']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{x:02x}' for x in data[i:i + 16]) + ',')
    lines += ['];', '',
              '/// Offsets of the four WRPKRU instructions, in order (G, E, G, C).',
              'pub const WRPKRU: [usize; 4] = [' + ', '.join(f'{x:#x}' for x in wr) + '];',
              '/// Offset right after the call into the callee (the callee returns here).',
              f'pub const RETURN: usize = {syms["gate_return"]:#x};',
              '',
              '/// (field, offset, width in bytes, addend) for every patch site.',
              'pub const SITES: &[(Field, usize, u8, u32)] = &[']
    for name, at, width, addend in sites:
        variant = ''.join(p.capitalize() for p in name.lower().split('_'))
        lines.append(f'    (Field::{variant}, {at:#x}, {width}, {addend:#x}),')
    lines += ['];', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT.relative_to(ROOT)} is stale; run scripts/gen_gate_stub.py')
            return 1
        print('[gate.stub] template up to date')
        return 0
    OUT.write_text(text)
    print(f'[gate.stub] wrote {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
