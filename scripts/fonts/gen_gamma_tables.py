"""Writes crates/sex-font/src/gamma_tables.rs: sRGB <-> linear light in integers.

sex-font is no_std and integer-only, so the transfer curves are tables: 256 sRGB
levels to 12-bit linear light, and 4096 linear levels back to sRGB bytes.
Run again only if the table sizes change; the output is checked in.
"""
from pathlib import Path


def to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def to_srgb(v):
    return v * 12.92 if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055


def main():
    lin = [round(to_linear(i / 255) * 4095) for i in range(256)]
    srgb = [round(to_srgb(i / 4095) * 255) for i in range(4096)]
    rows = lambda vals, n: '\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + n]) + ','
                                     for i in range(0, len(vals), n))
    out = Path(__file__).resolve().parents[2] / 'crates/sex-font/src/gamma_tables.rs'
    out.write_text(
        '// SPDX-License-Identifier: GPL-3.0-only\n'
        '// Generated by scripts/fonts/gen_gamma_tables.py. Do not edit.\n\n'
        '/// sRGB byte to linear light, 0..=4095.\n'
        f'pub static SRGB_TO_LINEAR: [u16; 256] = [\n{rows(lin, 16)}\n];\n\n'
        '/// Linear light 0..=4095 to an sRGB byte.\n'
        f'pub static LINEAR_TO_SRGB: [u8; 4096] = [\n{rows(srgb, 32)}\n];\n')


if __name__ == '__main__':
    main()
