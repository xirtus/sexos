#!/usr/bin/env python3
"""Renders Geist Mono into the anti-aliased glyph table Display draws text from:
one 12x18 cell per character, 8-bit coverage, ASCII and the Unicode letters Display
already knows. The output is Rust source in sex-pdx, committed beside the font."""
import re
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'assets/fonts/geist/GeistMono-Regular.ttf'
SANS=ROOT/'assets/fonts/geist/Geist-Regular.ttf'
OUT=ROOT/'crates/sex-pdx/src/font_geist.rs'
# 19 px keeps descenders inside the 18-pixel line; the advance (11.4) fits the 12-pixel cell.
W,H,SIZE,RISE=12,18,19,-5
def cell(font,ch):
 img=Image.new('L',(W,H),0);ImageDraw.Draw(img).text((0,RISE),ch,font=font,fill=255)
 return img.tobytes()
def main():
 font=ImageFont.truetype(str(FONT),SIZE)
 display=(ROOT/'servers/sexdisplay/src/main.rs').read_text()
 extra=sorted({int(c,16) for c in re.findall(r'\(0x([0-9A-Fa-f]+), \[',display[display.index('const FONT_UNICODE_5X7'):display.index('];',display.index('const FONT_UNICODE_5X7'))])})
 # Only letters Geist actually has: a missing one renders as .notdef, which is worse than the old box.
 known=[c for c in extra if c==0xA0 or font.getmask(chr(c)).getbbox() and font.getbbox(chr(c))!=font.getbbox('￿')]
 rows=lambda b:'['+','.join(str(v) for v in b)+']'
 out=['// SPDX-License-Identifier: GPL-3.0-only','//! Geist Mono (Vercel, SIL Open Font License 1.1) as 12x18 cells of 8-bit coverage.',
  '//! Generated by scripts/make_font.py from assets/fonts/geist; do not edit by hand.',
  f'pub const CELL_W: usize = {W};',f'pub const CELL_H: usize = {H};',
  f'pub static ASCII: [[u8; {W*H}]; 95] = [']
 out+=['    '+rows(cell(font,chr(c)))+',' for c in range(32,127)]
 out+=['];',f'pub static EXTRA: [(u32, [u8; {W*H}]); {len(known)}] = [']
 out+=[f'    (0x{c:04X}, '+rows(cell(font,chr(c)))+'),' for c in known]
 # Geist Sans for window titles: proportional, so each glyph keeps its own advance.
 sans=ImageFont.truetype(str(SANS),17);TW,TH=18,18
 out+=['];','/// Geist Sans at title size: (advance, 18x18 coverage) per ASCII character.',
  f'pub const TITLE_W: usize = {TW};',f'pub const TITLE_H: usize = {TH};',f'pub static TITLE: [(u8, [u8; {TW*TH}]); 95] = [']
 for c in range(32,127):
  img=Image.new('L',(TW,TH),0);ImageDraw.Draw(img).text((0,-3),chr(c),font=sans,fill=255)
  out.append(f'    ({round(sans.getlength(chr(c)))}, '+rows(img.tobytes())+'),')
 out+=['];','/// The cell for a scalar, if Geist has it.','pub fn cell(scalar: u32) -> Option<&\'static [u8; CELL_W * CELL_H]> {',
  '    if (32..=126).contains(&scalar) { return Some(&ASCII[(scalar - 32) as usize]); }',
  '    EXTRA.iter().find(|(c, _)| *c == scalar).map(|(_, g)| g)','}','']
 OUT.write_text('\n'.join(out))
 print(OUT,len(known),'extra of',len(extra))
if __name__=='__main__':main()
