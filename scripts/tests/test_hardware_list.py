"""scripts/hardware_list.py: the public hardware list is built from sex-hwdb and
real-machine reports, misses no table row, and stays in step with its sources."""
import os
import re
import shutil
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import hardware_list  # noqa: E402

SAMPLE = os.path.join(HERE, "fixtures", "hw_report_x17_sample.txt")


class HardwareList(unittest.TestCase):
    def setUp(self):
        with open(hardware_list.HWDB) as f:
            self.src = f.read()

    def test_every_table_row_is_listed(self):
        devices, _, _ = hardware_list.hwdb(self.src)
        body = hardware_list._fn_body(self.src, "exact")
        ids = sum(len(re.findall(r"\(0x[0-9a-fA-F]{4},\s*0x[0-9a-fA-F]{4}\)", l.split("=>")[0]))
                  for l in body.splitlines() if "known(" in l and not l.strip().startswith("//"))
        self.assertEqual(len(devices), ids)
        self.assertGreater(len(devices), 40)
        x17_gpu = next(d for d in devices if (d["vendor"], d["device"]) == ("10de", "24dd"))
        self.assertEqual((x17_gpu["vendor_name"], x17_gpu["service"]), ("NVIDIA", "Display"))
        self.assertIn(x17_gpu["support"], hardware_list.SUPPORT)

    def test_class_rules_cover_every_arm(self):
        _, classes, _ = hardware_list.hwdb(self.src)
        body = hardware_list._strip_comments(hardware_list._fn_body(self.src, "by_class"))
        arms = sum(max(1, len(re.findall(r"\((?:0x[0-9a-f]{2}|_), (?:0x[0-9a-f]{2}|_), (?:0x[0-9a-f]{2}|_)\)", l.split(" => ")[0])))
                   for l in body.splitlines() if " => (" in l)
        self.assertEqual(len(classes), arms)
        self.assertEqual(classes[-1]["name"], "anything else")
        nvme = next(c for c in classes if (c["class"], c["subclass"]) == ("0x01", "0x08"))
        self.assertEqual((nvme["service"], nvme["support"]), ("Drive", "Driven"))
        hda = [c for c in classes if (c["class"], c["subclass"]) == ("0x04", "0x03")]
        self.assertEqual(hda[0]["only"], "not NVIDIA or AMD/ATI")

    def test_real_machine_reports_fill_seen_on(self):
        tmp = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(tmp, "x17r1"))
            with open(SAMPLE) as f, open(os.path.join(tmp, "x17r1", "2026-11-20-1.txt"), "w") as g:
                g.write(f.read() + "[hw.device] 00:1f.4 8086:43a3 class=0c0500 Intel SMBus controller service=kernel support=platform\n")
            data = hardware_list.build(self.src, tmp)
            self.assertEqual([m["machine"] for m in data["machines"]], ["x17r1"])
            igpu = next(d for d in data["devices"] if (d["vendor"], d["device"]) == ("8086", "9a60"))
            self.assertEqual(igpu["seen"], [{"machine": "x17r1", "support_reported": "intel_display", "check": "display", "state": "ok"}])
            gpu = next(d for d in data["devices"] if (d["vendor"], d["device"]) == ("10de", "24dd"))
            self.assertEqual(gpu["seen"][0]["check"], "gpu")
            # A device the table does not name is listed with its class.
            self.assertEqual([(u["id"], u["class"]) for u in data["unlisted"]], [("8086:43a3", "0c0500")])
            md = hardware_list.markdown(data)
            self.assertIn("| x17r1 | `hw-reports/x17r1/2026-11-20-1.txt` |", md)
            self.assertIn("x17r1: works", md)
            self.assertIn("## Seen on real machines, not named in the table", md)
            # Deterministic.
            self.assertEqual(md, hardware_list.markdown(hardware_list.build(self.src, tmp)))
        finally:
            shutil.rmtree(tmp)

    def test_kernel_census_line_shape(self):
        # The kernel's [hw.device] line (kernel/src/devmgr.rs census_line) carries
        # class= and support= fields; the list reads both.
        tmp = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(tmp, "qemu"))
            with open(os.path.join(tmp, "qemu", "2026-11-20-1.txt"), "w") as f:
                f.write("[hw.device] 00:04.0 1b36:0010 class=010802 QEMU NVMe controller (QEMU) service=sexdrive support=driven\n"
                        "[sexdrive.nvme.drive] model=QEMU\n")
            data = hardware_list.build(self.src, tmp)
            nvme = next(d for d in data["devices"] if (d["vendor"], d["device"]) == ("1b36", "0010"))
            self.assertEqual(nvme["seen"], [{"machine": "qemu", "support_reported": "driven", "check": "nvme", "state": "ok"}])
        finally:
            shutil.rmtree(tmp)

    def test_published_list_matches_the_table(self):
        # docs/HARDWARE.md names every device in sex-hwdb. It is regenerated by
        # `python3 scripts/hardware_list.py`; a row added to the table without
        # regenerating shows in the CI summary (hardware_list.py --check), and
        # only a device missing from the published list fails here.
        with open(hardware_list.OUT_MD) as f:
            md = f.read()
        devices, _, _ = hardware_list.hwdb(self.src)
        missing = [f"{d['vendor']}:{d['device']}" for d in devices if f"`{d['vendor']}:{d['device']}`" not in md]
        self.assertLessEqual(len(missing), 5, f"docs/HARDWARE.md is far behind sex-hwdb; run scripts/hardware_list.py ({missing})")


if __name__ == "__main__":
    unittest.main()
