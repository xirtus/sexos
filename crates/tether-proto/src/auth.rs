//! Self-contained no_std SHA-256, HMAC-SHA256, FNV-64, and PIN pairing auth for Tether v2.

/// FNV-1a 64-bit offset basis (matches `sex_pdx::crash_log::FNV64_OFFSET`).
pub const FNV64_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
pub const FNV64_PRIME: u64 = 0x0000_0100_0000_01b3;

pub fn fnv64_update(mut h: u64, bytes: &[u8]) -> u64 {
    for &b in bytes {
        h ^= b as u64;
        h = h.wrapping_mul(FNV64_PRIME);
    }
    h
}

pub fn fnv64(bytes: &[u8]) -> u64 {
    fnv64_update(FNV64_OFFSET, bytes)
}

/// Constant-time 32-byte comparison.
pub fn ct_eq_32(a: &[u8; 32], b: &[u8; 32]) -> bool {
    let mut diff = 0u8;
    for i in 0..32 {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

