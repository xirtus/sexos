#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_arpabet_en_contains_15_vowels() {
        let vowels = [
            "AA", "AE", "AH", "AO", "AW", "AY", "EH", "ER", "EY", "IH", "IY", "OW", "OY", "UH",
            "UW",
        ];
        assert_eq!(vowels.len(), 15);
        for v in vowels {
            let found = lookup_phoneme("en", v);
            assert!(found.is_some(), "Missing ARPABET vowel: {}", v);
            let p = found.unwrap();
            assert_eq!(p.voicing, 1.0, "Vowel {} must be voiced", v);
            assert!(p.f1 > 200.0 && p.f1 < 900.0);
            assert!(p.f2 > 700.0 && p.f2 < 2600.0);
        }
    }

    #[test]
    fn test_arpabet_en_contains_24_consonants() {
        let consonants = [
            "B", "CH", "D", "DH", "F", "G", "HH", "JH", "K", "L", "M", "N", "NG", "P", "R", "S",
            "SH", "T", "TH", "V", "W", "Y", "Z", "ZH",
        ];
        assert_eq!(consonants.len(), 24);
        for c in consonants {
            let found = lookup_phoneme("en", c);
            assert!(found.is_some(), "Missing ARPABET consonant: {}", c);
        }
        assert_eq!(ARPABET_EN.len(), 39);
    }

    #[test]
    fn test_ja_mokhtari_bank() {
        let ja_phones = ["A", "I", "U", "E", "O", "N", "R", "TS", "SH", "CH", "F"];
        for code in ja_phones {
            let found = lookup_phoneme("ja", code);
            assert!(found.is_some(), "Missing Japanese phone: {}", code);
        }
        let a = lookup_phoneme("ja", "A").unwrap();
        assert_eq!(a.f1, 760.0);
        assert_eq!(a.f2, 1250.0);
    }

    #[test]
    fn test_lookup_phoneme_fallback_and_case() {
        assert_eq!(
            lookup_phoneme("EN", "iy"),
            Some(ARPABET_EN.iter().find(|p| p.code == "IY").unwrap())
        );
        assert_eq!(
            lookup_phoneme("", "ER"),
            Some(ARPABET_EN.iter().find(|p| p.code == "ER").unwrap())
        );
        assert_eq!(
            lookup_phoneme("ja", "ts"),
            Some(JA_MOKHTARI_2000.iter().find(|p| p.code == "TS").unwrap())
        );
        assert!(lookup_phoneme("en", "XYZ").is_none());
    }

    #[test]
    fn test_ariel_canned_presets() {
        assert!(
            ARIEL_CANNED_PRESETS.len() >= 8,
            "Expected at least 8 presets"
        );
        for (name, seq) in ARIEL_CANNED_PRESETS {
            assert!(!name.is_empty());
            assert!(!seq.is_empty());
            // Verify all tokens exist in the phoneme tables
            let mut bank = "en";
            for token in seq.split_whitespace() {
                if token.starts_with("[bank=") && token.ends_with(']') {
                    bank = &token[6..token.len() - 1];
                    continue;
                }
                assert!(
                    lookup_phoneme(bank, token).is_some(),
                    "Preset {} has unknown phoneme token: {} in bank {}",
                    name,
                    token,
                    bank
                );
            }
        }
    }
}
