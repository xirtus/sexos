/// Look up a phoneme specification from the requested bank.
/// Supported banks: "en" / "arpabet" / "arpabet_en", "ja" / "japanese" / "ja_mokhtari_2000",
/// or "" / "any" / "default" to fall back across banks.
pub fn lookup_phoneme(bank: &str, code: &str) -> Option<&'static PhonemeSpec> {
    let clean_code = code.trim();
    if clean_code.is_empty() {
        return None;
    }
    let b = bank.trim();
    if b.eq_ignore_ascii_case("en")
        || b.eq_ignore_ascii_case("arpabet")
        || b.eq_ignore_ascii_case("arpabet_en")
    {
        return ARPABET_EN
            .iter()
            .find(|p| p.code.eq_ignore_ascii_case(clean_code));
    }
    if b.eq_ignore_ascii_case("ja")
        || b.eq_ignore_ascii_case("japanese")
        || b.eq_ignore_ascii_case("ja_mokhtari_2000")
    {
        return JA_MOKHTARI_2000
            .iter()
            .find(|p| p.code.eq_ignore_ascii_case(clean_code));
    }

    // Default or empty bank: search English first, then Japanese.
    ARPABET_EN
        .iter()
        .find(|p| p.code.eq_ignore_ascii_case(clean_code))
        .or_else(|| {
            JA_MOKHTARI_2000
                .iter()
                .find(|p| p.code.eq_ignore_ascii_case(clean_code))
        })
}

