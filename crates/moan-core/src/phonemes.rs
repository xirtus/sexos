extern crate alloc;

/// Acoustic and articulatory specification of a speech phoneme for formant synthesis.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PhonemeSpec {
    /// Phonemic code (e.g., "AA", "IY", "S", "CH").
    pub code: &'static str,
    /// First formant frequency in Hz.
    pub f1: f32,
    /// First formant bandwidth in Hz.
    pub bw1: f32,
    /// First formant linear amplitude target (0.0 .. 1.0).
    pub a1: f32,
    /// Second formant frequency in Hz.
    pub f2: f32,
    /// Second formant bandwidth in Hz.
    pub bw2: f32,
    /// Second formant linear amplitude target (0.0 .. 1.0).
    pub a2: f32,
    /// Third formant frequency in Hz.
    pub f3: f32,
    /// Third formant bandwidth in Hz.
    pub bw3: f32,
    /// Third formant linear amplitude target (0.0 .. 1.0).
    pub a3: f32,
    /// Glottal voicing excitation strength (0.0 = unvoiced/whisper, 1.0 = fully voiced).
    pub voicing: f32,
    /// Frication/aspiration noise excitation strength (0.0 = pure tone, 1.0 = strong noise).
    pub aspiration: f32,
    /// Nominal intrinsic duration multiplier relative to standard phone length.
    pub duration_mult: f32,
    /// Canonical English example word demonstrating this phone.
    pub example_word: &'static str,
}

